"""Generate reconstruction/INDEX.md, the one status table of reconstructed functions.

    python3 tools/build_index.py           # rewrite the index from the data
    python3 tools/build_index.py --check   # exit 1 if the committed index is out of date

One row per inventory entry, derived from data/progress.json, the match records and the Reviewer
records; nothing in it is typed by hand, so acceptance, revocation and staleness cannot leave a
stale status row behind. tools/check.py fails when the file differs from what this renders, and
tools/accept_function.py rewrites it. The output holds no time stamp, so it changes only when the
data does.
"""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check import ROOT, _json_or_none, acceptance_staleness, review_record_path  # noqa: E402

INDEX = 'reconstruction/INDEX.md'
HEADER = """# Reconstruction index

Generated by `tools/build_index.py` from `data/progress.json`, the match records and the Reviewer
records under `reports/`. Do not edit it by hand: `tools/check.py` fails when it is out of date,
and `tools/accept_function.py` rewrites it. A byte match covers the checked code only; it does not
verify a name or behaviour. Status `STALE` means the function's unit or review no longer binds the
integrated source (`docs/verification.md`, "Stale acceptances and delta reviews").

| unit | function (name origin) | build / RVA / size | recipe | record | status | review |
|---|---|---|---|---|---|---|
"""


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def row(fn, root):
    record = _json_or_none(root / fn['report']) if isinstance(fn.get('report'), str) else None
    source = (record or {}).get('source') or {}
    compiled = source.get('compiled')
    unit = f'`{compiled.removeprefix("reconstruction/").removesuffix(".cpp")}`' if isinstance(compiled, str) else '-'
    recipe_path = ((record or {}).get('recipe') or {}).get('path')
    recipe = f'`{Path(recipe_path).stem}`' if isinstance(recipe_path, str) else '-'
    status = fn['status']
    if record is not None and status != 'matched':
        status += ', record awaiting review'
    stale = acceptance_staleness(fn, root) if fn['status'] == 'matched' else None
    if stale:
        status += f', STALE ({stale})'
    review = _json_or_none(root / review_record_path(fn)) if fn['status'] == 'matched' else None
    kind = '-' if review is None else review.get('review_kind', 'full')
    return (f'| {unit} | `{cell(fn["name"])}` ({cell(fn["name_origin"])}) | `{fn["build_id"]}` / '
            f'`0x{fn["rva"]:x}` / {fn["size"]} | {recipe} | '
            f'{"`" + cell(fn["report"]) + "`" if record is not None else "-"} | {status} | {kind} |\n')


def render_index(data, root=ROOT):
    root = Path(root)
    functions = sorted(data['functions'], key=lambda fn: (fn['build_id'], fn['rva']))
    return HEADER + ''.join(row(fn, root) for fn in functions)


def write_index(data, root=ROOT):
    (Path(root) / INDEX).write_text(render_index(data, root))
    return INDEX


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true', help='Exit 1 if the index is out of date; write nothing')
    p.add_argument('--root', type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = p.parse_args(argv)
    data = json.loads((args.root / 'data/progress.json').read_text())
    path = args.root / INDEX
    if args.check:
        current = path.read_text() if path.is_file() else None
        if current != render_index(data, args.root):
            print(f'{INDEX} is out of date; run python3 tools/build_index.py', file=sys.stderr)
            return 1
        print(f'{INDEX} is up to date')
        return 0
    write_index(data, args.root)
    print(f'wrote {INDEX}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
