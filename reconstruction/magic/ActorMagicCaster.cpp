// RVA 0x5c1260, 8 bytes, ActorMagicCaster::SetSkipCheckCast.
void ActorMagicCaster::SetSkipCheckCast()
{
    castFlags.all |= 2u;
}

// RVA 0x5c1b10, 8 bytes, ActorMagicCaster::GetCasterStatsObject.
